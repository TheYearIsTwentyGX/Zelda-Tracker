TOWER_STROKE = 7.8


def path(data: str, fill: str | None = None, stroke: str | None = None, width: float = 0.0,
         even_odd: bool = False) -> str:
    attrs = [f'android:pathData="{data}"']
    if fill:
        attrs.append(f'android:fillColor="{fill}"')
    if even_odd:
        attrs.append('android:fillType="evenOdd"')
    if stroke:
        attrs += [f'android:strokeColor="{stroke}"', f'android:strokeWidth="{width}"',
                  'android:strokeLineJoin="round"']
    return "        <path " + "\n            ".join(attrs) + " />"


def vector(size_dp: int, viewport: float, paths: list[str], source: str) -> str:
    """A square vector drawable showing [viewport] units around the icons' centre (533.2, 533.2)."""
    offset = round(533.2 - viewport / 2, 1)
    return "\n".join([
        f"<!-- Generated by scripts/build-map-icons.py from objmap's {source}; see docs/map-icons.md. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{size_dp}dp"',
        f'    android:height="{size_dp}dp"',
        f'    android:viewportWidth="{viewport}"',
        f'    android:viewportHeight="{viewport}">',
        f'    <group android:translateX="{-offset}" android:translateY="{-offset}">',
        *paths,
        "    </group>",
        "</vector>",
        "",
    ])


def shrine(glyph: str, glyph_color: str, source: str) -> str:
    # Frame first, then the glyph and its outline on top, so the DLC spire covers the frame.
    return vector(24, 600, [
        path(f"{OUTER}{INNER}", fill=BLUE, stroke=OUTLINE, width=SHRINE_STROKE, even_odd=True),
        path(f"{glyph}{KEYHOLE}", fill=glyph_color, stroke=OUTLINE, width=SHRINE_STROKE, even_odd=True),
    ], source)


def tower(color: str) -> str:
    return vector(24, 680, [path(TOWER, fill=color, stroke=OUTLINE, width=TOWER_STROKE)], "mapicon_tower.svg")


