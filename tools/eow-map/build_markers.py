#!/usr/bin/env python3
"""
Build the Echoes of Wisdom map markers (Pieces of Heart, Heart Containers, Stamp Stands, Might
Crystals) from the game's own map pins.

    python3 tools/eow-map/build_markers.py                 download (once), validate, write markers.json
    python3 tools/eow-map/build_markers.py --offline       use only tools/eow-map/.cache/
    python3 tools/eow-map/build_markers.py --cross-check   also compare with Zelda Dungeon's map

Positions come from MrCheeze/eow-tools (pinned at EOW_TOOLS_SHA), in world units (x east, z south):
- Pieces of Heart: UiMapIconItem row "HeartPiece", icon i = key "HeartPiece i".
- Might Crystals: UiMapIconItem row "WorldGlobePiece", icon i = PieceOfPowers row i (key PieceNNN,
  mCount = crystals). Rows with mCount 0 are unused.
- Stamp Stands: the StampTable actors in level Field.json, keyed by their Stamp_NN parameter.
- Heart Containers have no pin of their own: each reuses its dungeon's x5 crystal pin (column `at`).

Which pin belongs to which checklist item is decided by hand in matches.tsv (one row per item:
key, file, item, confidence, evidence, optional `at` = a pin key or "x,z" for keys that are not
pins). The evidence column says why. This script only looks positions up and checks the table:
every item of the mapped sections exactly once, every pin used exactly once, ids exist, and a
crystal pin's count equals the item's `value`.

--cross-check compares every pin with Zelda Dungeon's interactive map (tools/eow-map/.cache/
zd_items.json, a copy of its items layer, if present): it stores lng = 1.67 x - 554 and
lat = -1.67 z + 399. Stdlib only.
"""

import argparse
import json
import math
import sys
import urllib.request
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
CACHE = HERE / ".cache"
FILES = ROOT / "shared/src/commonMain/composeResources/files/eow"
OUT = FILES / "map/markers.json"
MATCHES = HERE / "matches.tsv"

EOW_TOOLS_SHA = "e6a309a41a4766cd047418e905308474b90085e3"
RAW = f"https://raw.githubusercontent.com/MrCheeze/eow-tools/{EOW_TOOLS_SHA}/"
SOURCES = {
    "UiMapIconItem.json": "gsheet_json/1.0.1-2/datasheets/ui/UiMapIconItem.json",
    "PieceOfPowers.json": "gsheet_json/1.0.1-2/datasheets/PieceOfPowers.json",
    "Field.json": "level_json/1.0.2/Field.json",
}
USER_AGENT = "ZeldaGX-eow-map/1.0 (one-off fetch for a personal offline tracker app)"

# Checklist sections that get map markers, in output order.
SECTIONS = [
    ("heart_pieces", "pieces"),
    ("heart_pieces", "containers"),
    ("stamp_stands", "stands"),
    ("might_crystals", "crystals"),
]

COMMENT = (
    "Generated by tools/eow-map/build_markers.py from tools/eow-map/matches.tsv. "
    "Positions: the game's map pins (github.com/MrCheeze/eow-tools), world units, x east, z south."
)


def fetch(name, offline):
    path = CACHE / name
    if path.exists():
        return path
    if offline:
        sys.exit(f"--offline but {path} isn't cached")
    CACHE.mkdir(parents=True, exist_ok=True)
    url = RAW + SOURCES[name]
    print(f"fetching {url}")
    data = urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": USER_AGENT}), timeout=120).read()
    path.write_bytes(data)
    return path


def load_pins(offline):
    """Every pin key -> (x, z, crystal count or None)."""
    icons = {r["mSymbol"]: r["mIconInfos"] for r in json.loads(fetch("UiMapIconItem.json", offline).read_text())["rows"]}
    pins = {}
    for i, icon in enumerate(icons["HeartPiece"]):
        pins[f"HeartPiece {i}"] = (icon["mPosX"], icon["mPosY"], None)
    powers = json.loads(fetch("PieceOfPowers.json", offline).read_text())["rows"]
    globes = icons["WorldGlobePiece"]
    if len(powers) != len(globes):
        sys.exit(f"PieceOfPowers has {len(powers)} rows but WorldGlobePiece has {len(globes)} icons")
    for row, icon in zip(powers, globes):
        if row["mCount"] > 0:
            pins[row["mKey"]] = (icon["mPosX"], icon["mPosY"], row["mCount"])
    actors = json.loads(fetch("Field.json", offline).read_text())["actors"]
    for actor in actors:
        if actor[13] != "StampTable":
            continue
        keys = [p for p in actor[8] if isinstance(p, str) and p.startswith("Stamp_")]
        if len(keys) != 1 or keys[0] in pins:
            sys.exit(f"unexpected StampTable actor parameters: {actor[8]}")
        pins[keys[0]] = (actor[0][0], actor[0][2], None)
    return pins


def load_matches():
    rows = []
    lines = MATCHES.read_text().splitlines()
    header = lines[0].split("\t")
    if header[:5] != ["key", "file", "item", "confidence", "evidence"]:
        sys.exit(f"{MATCHES.name}: unexpected header {header}")
    for n, line in enumerate(lines[1:], start=2):
        if not line.strip():
            continue
        cols = line.split("\t")
        if len(cols) not in (5, 6):
            sys.exit(f"{MATCHES.name}:{n}: expected 5 or 6 columns, got {len(cols)}")
        key, file, item, confidence, evidence = cols[:5]
        at = cols[5] if len(cols) == 6 else ""
        if confidence not in ("high", "medium", "low"):
            sys.exit(f"{MATCHES.name}:{n}: bad confidence {confidence!r}")
        rows.append({"line": n, "key": key, "file": file, "item": item, "confidence": confidence, "evidence": evidence, "at": at})
    return rows


def load_items():
    """(file, item id) -> item, in checklist order."""
    items = {}
    for file, section in SECTIONS:
        data = json.loads((FILES / f"{file}.json").read_text())
        found = [s for s in data["sections"] if s["id"] == section]
        if len(found) != 1:
            sys.exit(f"{file}.json: section {section!r} not found")
        for item in found[0]["items"]:
            items[(file, item["id"])] = item
    return items


def build(pins, rows, items):
    errors = []
    by_item = {}
    for row in rows:
        ident = (row["file"], row["item"])
        if ident not in items:
            errors.append(f"line {row['line']}: {row['file']}/{row['item']} is not in a mapped section")
        elif ident in by_item:
            errors.append(f"line {row['line']}: {row['file']}/{row['item']} listed twice")
        by_item[ident] = row
    for ident in items:
        if ident not in by_item:
            errors.append(f"{ident[0]}/{ident[1]} has no row")

    keys = Counter(row["key"] for row in rows)
    for key, n in keys.items():
        if n > 1:
            errors.append(f"key {key!r} used {n} times")
    pin_uses = Counter()
    for row in rows:
        if row["key"] in pins:
            if row["at"]:
                errors.append(f"line {row['line']}: {row['key']} is a pin, it takes no `at`")
            pin_uses[row["key"]] += 1
        elif row["at"]:
            if row["at"] not in pins and len(row["at"].split(",")) != 2:
                errors.append(f"line {row['line']}: `at` {row['at']!r} is neither a pin key nor x,z")
        else:
            errors.append(f"line {row['line']}: {row['key']!r} is not a pin and has no `at`")
    for key in pins:
        if pin_uses[key] == 0:
            errors.append(f"pin {key} is not used")

    markers = []
    for (file, item_id), item in items.items():
        row = by_item.get((file, item_id))
        if row is None:
            continue
        if row["key"] in pins:
            x, z, count = pins[row["key"]]
            if file == "might_crystals":
                if count != item.get("value", 1):
                    errors.append(f"line {row['line']}: {row['key']} holds {count} crystals but {item_id} is worth {item.get('value', 1)}")
            elif count is not None:
                errors.append(f"line {row['line']}: crystal pin {row['key']} used for {file}/{item_id}")
        elif row["at"] in pins:
            x, z, _ = pins[row["at"]]
        elif row["at"]:
            x, z = (float(v) for v in row["at"].split(","))
        else:
            continue
        markers.append({"file": file, "item": item_id, "key": row["key"], "x": round(float(x), 4), "z": round(float(z), 4)})
    return markers, errors


def cross_check(pins):
    path = CACHE / "zd_items.json"
    if not path.exists():
        print(f"cross-check: {path} not found, skipped")
        return
    zd = []
    for category in json.loads(path.read_text()):
        for layer in category["layers"]:
            for m in layer["markers"]:
                lat, lng = m["coords"]
                zd.append((m["id"], (lng + 554) / 1.67, (399 - lat) / 1.67))
    worst, unmatched = (0.0, None, None), []
    for key, (x, z, _) in pins.items():
        best = min(zd, key=lambda m: math.hypot(m[1] - x, m[2] - z))
        d = math.hypot(best[1] - x, best[2] - z)
        if d > 1.0:
            unmatched.append(f"{key} (nearest {best[0]} at {d:.2f} u)")
        if d > worst[0]:
            worst = (d, key, best[0])
    print(f"cross-check: {len(pins)} pins vs {len(zd)} Zelda Dungeon markers; max residual {worst[0]:.3f} u ({worst[1]} ~ {worst[2]})")
    for line in unmatched:
        print(f"  no Zelda Dungeon marker within 1 u: {line}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--offline", action="store_true", help="use only the cached eow-tools files")
    ap.add_argument("--cross-check", action="store_true", help="compare the pins with the cached Zelda Dungeon items layer")
    args = ap.parse_args()

    pins = load_pins(args.offline)
    rows = load_matches()
    items = load_items()
    markers, errors = build(pins, rows, items)
    if errors:
        for e in errors:
            print("error:", e, file=sys.stderr)
        sys.exit(f"{len(errors)} error(s); markers.json not written")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    body = ",\n".join("    " + json.dumps(m, ensure_ascii=False) for m in markers)
    OUT.write_text(
        "{\n"
        f'  "_comment": {json.dumps(COMMENT)},\n'
        f'  "markers": [\n{body}\n  ],\n'
        '  "unplaced": []\n'
        "}\n"
    )
    per_file = Counter(m["file"] for m in markers)
    conf = Counter(r["confidence"] for r in rows)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(markers)} markers ({dict(per_file)}); confidence {dict(conf)}")
    if args.cross_check:
        cross_check(pins)


if __name__ == "__main__":
    main()
